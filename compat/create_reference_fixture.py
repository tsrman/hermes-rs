#!/usr/bin/env python3
"""Create a disposable Hermes profile using the pinned Python storage API."""

import argparse
import os
import sqlite3
import subprocess
import sys
from contextlib import closing
from pathlib import Path

REFERENCE_COMMIT = "2f8c1e7ed051c311af4f3b3ca0f8976b9c40839b"
LEGACY_REFERENCE_COMMIT = "10d25f8ad65fdf71304e9272959421a0c22e5d23"
VERSIONS = {32: LEGACY_REFERENCE_COMMIT, 33: REFERENCE_COMMIT}
REFERENCE_MESSAGES = [("user", "Привет, Hermes"), ("assistant", "Здравствуйте!")]


def export_schema(db, checkout, commit, destination):
    shadow_tables = {name for _, name, kind, *_ in db.execute("PRAGMA table_list") if kind == "shadow"}
    ddl = db.execute("SELECT name, sql FROM sqlite_schema WHERE sql IS NOT NULL ORDER BY rowid")
    license_text = (checkout / "LICENSE").read_text(encoding="utf-8")
    with destination.open("x", encoding="utf-8") as output:
        output.write(f"-- Schema from NousResearch/hermes-agent at {commit}.\n")
        output.write("-- Generated by compat/create_reference_fixture.py --schema-out.\n\n")
        output.write("\n".join(f"-- {line}".rstrip() for line in license_text.splitlines()) + "\n\n")
        statements = (statement for name, statement in ddl
                      if name not in shadow_tables and not name.startswith("sqlite_"))
        output.write(";\n\n".join(statements) + ";\n")


def create_current_fixture(profile):
    from persistence.conversation.messages import NewMessage
    from persistence.conversation.sessions import NewSession
    from persistence_assembly import open_persistence, profile_scope

    with open_persistence(profile_scope(home=profile)) as store:
        store.sessions.create(NewSession(session_id="compat-session", source="cli"))
        for role, content in REFERENCE_MESSAGES:
            store.messages.append("compat-session", NewMessage.from_live({"role": role, "content": content}))


def create_legacy_fixture(profile):
    from hermes_state import SessionDB

    with closing(SessionDB(profile / "state.db")) as store:
        store.create_session("compat-session", "cli")
        for role, content in REFERENCE_MESSAGES:
            store.append_message("compat-session", role, content)

        parent = "compat-legacy-root"
        store.create_session(parent, "cli")
        store.append_message(parent, "user", "архивный запрос", display_metadata={"fixture": "v32"})
        store.archive_and_compact(parent, [{"role": "user", "content": "сводка", "_compressed_summary": True}])
        store.end_session(parent, "compression")

        store.create_session("compat-legacy-tip", "cli", parent_session_id=parent)
        store.append_message("compat-legacy-tip", "assistant", "продолжение диалога")
        store.create_session("compat-legacy-delegate", "subagent", parent_session_id=parent)
        store.append_message("compat-legacy-delegate", "assistant", "отдельный ответ субагента")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("checkout", type=Path, help="Pinned Hermes Python checkout")
    parser.add_argument("profile", type=Path, help="New empty directory for fixture data")
    parser.add_argument("--schema-version", type=int, choices=VERSIONS, default=33)
    parser.add_argument("--schema-out", type=Path, help="Export the pinned schema to a new SQL file")
    args = parser.parse_args()

    checkout = args.checkout.resolve(strict=True)
    head = subprocess.check_output(
        ["git", "rev-parse", "HEAD"], cwd=checkout, text=True
    ).strip()
    expected = VERSIONS[args.schema_version]
    if head != expected:
        parser.error(f"expected upstream commit {expected}, got {head}")
    profile = args.profile.resolve()
    profile.mkdir(parents=True, exist_ok=False)
    os.environ["HERMES_HOME"] = str(profile)
    sys.path.insert(0, str(checkout))

    create_fixture = create_legacy_fixture if args.schema_version == 32 else create_current_fixture
    create_fixture(profile)

    with closing(sqlite3.connect((profile / "state.db").as_uri() + "?mode=ro", uri=True)) as db:
        assert db.execute("SELECT version FROM schema_version").fetchall() == [(args.schema_version,)]
        rows = db.execute(
            "SELECT role, content FROM messages WHERE session_id = ? ORDER BY id",
            ("compat-session",),
        ).fetchall()
        assert rows == REFERENCE_MESSAGES
        assert db.execute("PRAGMA integrity_check").fetchone()[0] == "ok"
        if args.schema_out:
            export_schema(db, checkout, head, args.schema_out)
    print(profile / "state.db")


if __name__ == "__main__":
    main()
