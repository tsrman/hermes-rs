#!/usr/bin/env python3
"""Emit the approval detector's pattern tables as Rust source, straight from the reference.

Usage: generate_approval_tables.py <reference checkout> <hardline.rs> [<dangerous.rs>]

Nothing is executed: the module is imported to read its compiled-in pattern strings, which are
written as raw string constants so the port cannot drift from a hand copy.
"""

import os
import re
import sys
from pathlib import Path

os.environ["HOME"] = "/home/user"


def raw(text: str) -> str:
    hashes = "#"
    while f'"{hashes}' in text:
        hashes += "#"
    return f'r{hashes}"{text}"{hashes}'


def main():
    if len(sys.argv) not in (3, 4):
        sys.exit(__doc__)
    sys.path.insert(0, str(Path(sys.argv[1]).resolve()))
    from tools import approval_detection as d  # noqa: E402
    from tools import approval_windows_hardline as w  # noqa: E402

    out = [
        "//! Generated by `compat/generate_approval_tables.py` from the reference; do not edit by hand.",
        "",
        "/// `HARDLINE_PATTERNS`: (pattern, description, matched against the quote-masked variant).",
        "pub const HARDLINE_PATTERNS: &[(&str, &str, bool)] = &[",
    ]
    for pattern, description in d.HARDLINE_PATTERNS:
        masked = description in d._QUOTE_MASKED_HARDLINE_DESCRIPTIONS
        out.append(f"    ({raw(pattern)}, {raw(description)}, {str(masked).lower()}),")
    out.append("];")
    out += ["", "/// The `-WhatIf`-exempt rules without the exemption, by description.",
            "pub const WHATIF_STRICT_PATTERNS: &[(&str, &str)] = &["]
    for description, pattern in w.windows_whatif_strict_patterns(d._CMDPOS).items():
        out.append(f"    ({raw(description)}, {raw(pattern)}),")
    out.append("];")
    out += [
        "",
        f"pub const WHATIF_STATEMENT_UNGUARDED: &str = {raw(w._WHATIF_STATEMENT_UNGUARDED_RE.pattern)};",
        f"pub const WHATIF_OTHER_HARDLINE: &str = {raw(w._WHATIF_OTHER_HARDLINE_RE.pattern)};",
        "",
    ]
    Path(sys.argv[2]).write_text("\n".join(out), encoding="utf-8")
    print(f"{len(d.HARDLINE_PATTERNS)} hardline patterns, {len(w.windows_whatif_strict_patterns(d._CMDPOS))} strict")
    if len(sys.argv) == 4:
        write_dangerous(sys.argv[3], d)


FLAG_BITS = ((re.IGNORECASE, "i"), (re.MULTILINE, "m"), (re.DOTALL, "s"))


def with_flags(compiled) -> str:
    """The pattern with its Python flags as an inline `(?flags)` prefix."""
    letters = "".join(letter for bit, letter in FLAG_BITS if compiled.flags & bit)
    return (f"(?{letters})" if letters else "") + compiled.pattern


def write_dangerous(path: str, d) -> None:
    from tools import approval_fetch_exec as fe  # noqa: E402
    from tools import approval_wmic as wm  # noqa: E402

    out = [
        "//! Generated by `compat/generate_approval_tables.py` from the reference; do not edit by hand.",
        "",
        "/// `DANGEROUS_PATTERNS`: (pattern, description). Rows whose description names a custom matcher",
        "/// (pipe-to-shell, wmic, /dev/tcp, download-then-run) are not compiled as regexes.",
        "pub const DANGEROUS_PATTERNS: &[(&str, &str)] = &[",
    ]
    for pattern, description in d.DANGEROUS_PATTERNS:
        out.append(f"    ({raw(pattern)}, {raw(description)}),")
    out.append("];")

    def const(name, text):
        out.append(f"pub const {name}: &str = {raw(text)};")

    out.append("")
    for name, rx in (
        ("PIPE_BARE_SINK", d._PIPE_BARE_SINK_RE), ("PIPE_SINK", d._PIPE_SINK_RE),
        ("PIPE_LOOKUP_ONLY", d._PIPE_LOOKUP_ONLY_RE), ("PIPE_FETCH", d._PIPE_FETCH_RE),
        ("PIPE_OPERATOR", d._PIPE_OPERATOR_RE), ("PIPE_ONLY_OPERATOR", d._PIPE_ONLY_OPERATOR_RE),
        ("DEV_SOCKET", d._DEV_SOCKET_RE), ("DEV_SOCKET_REDIRECT_OP", d._DEV_SOCKET_REDIRECT_OP_RE),
        ("WMIC_DELETE_IN_SEGMENT", wm._WMIC_DELETE_IN_SEGMENT_RE), ("WMIC_CARRIER_SWITCHES", wm._CARRIER_SWITCHES_RE),
        ("WMIC_START_TITLE", wm._START_TITLE_RE), ("FETCH", fe._FETCH_RE), ("SEGMENT_END", fe._SEGMENT_END_RE),
        ("TARGET", fe._TARGET_RE), ("REDIRECT", fe._REDIRECT_RE), ("ARGS", fe._ARGS_RE), ("STDIN", fe._STDIN_RE),
        ("LOOKUP_ONLY", fe._LOOKUP_ONLY_RE), ("CURL_REMOTE_NAME", fe._CURL_REMOTE_NAME_RE), ("URL", fe._URL_RE),
        ("PS_READ_RUN", fe._PS_READ_RUN_RE), ("HIDDEN_VARIATION_SELECTOR", d._HIDDEN_VARIATION_SELECTOR_RE),
    ):
        const(name, with_flags(rx))
    matcher = fe.DownloadThenRunMatcher(d._SHELL_NAMES_RE)
    const("DOWNLOAD_RUN", with_flags(matcher._run_re))
    const("DOWNLOAD_READ_RUN", with_flags(matcher._read_run_re))
    const("SHELL_CHECK_FLAG", fe._SHELL_CHECK_FLAG)
    const("SHELL_VALUE_FLAG", fe._SHELL_VALUE_FLAG)
    out.append("pub const CHECK_ONLY_FLAGS: &[(&str, &str)] = &[")
    for name, pattern in fe._CHECK_ONLY_FLAGS.items():
        out.append(f"    ({raw(name)}, {raw(pattern)}),")
    out.append("];")
    out.append("pub const VALUE_FLAGS: &[(&str, &str)] = &[")
    for name, pattern in fe._VALUE_FLAGS.items():
        out.append(f"    ({raw(name)}, {raw(pattern)}),")
    out.append("];")
    out.append("pub const OPTION_WORDS: &[(&str, &str)] = &[")
    for name, pattern in fe._OPTION_WORDS.items():
        out.append(f"    ({raw(name)}, {raw(pattern)}),")
    out.append("];")
    out.append("")
    quoted = sorted(d._QUOTE_MASKED_DANGEROUS_DESCRIPTIONS)
    out.append("pub const QUOTE_MASKED_DANGEROUS: &[&str] = &[" + ", ".join(raw(x) for x in quoted) + "];")
    out.append("pub const PS_QUOTED_SCRIPT_LAUNCHERS: &[&str] = &[" + ", ".join(raw(x) for x in sorted(d._PS_QUOTED_SCRIPT_LAUNCHERS)) + "];")
    out.append("pub const CONTENT_RULE_DESCRIPTIONS: &[&str] = &[" + ", ".join(raw(x) for x in sorted(d._CONTENT_RULE_DESCRIPTIONS)) + "];")
    out.append("/// Description <-> legacy regex-derived approval key, both ways (stored allowlist entries).")
    out.append("pub const PATTERN_KEY_ALIASES: &[(&str, &[&str])] = &[")
    for key in sorted(d._PATTERN_KEY_ALIASES):
        values = ", ".join(raw(x) for x in sorted(d._PATTERN_KEY_ALIASES[key]))
        out.append(f"    ({raw(key)}, &[{values}]),")
    out.append("];")
    Path(path).write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{len(d.DANGEROUS_PATTERNS)} dangerous patterns")


if __name__ == "__main__":
    main()
