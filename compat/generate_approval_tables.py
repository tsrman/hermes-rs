#!/usr/bin/env python3
"""Emit the approval detector's pattern tables as Rust source, straight from the reference.

Usage: generate_approval_tables.py <reference checkout> <output.rs>

Nothing is executed: the module is imported to read its compiled-in pattern strings, which are
written as raw string constants so the port cannot drift from a hand copy.
"""

import os
import sys
from pathlib import Path

os.environ["HOME"] = "/home/user"


def raw(text: str) -> str:
    hashes = "#"
    while f'"{hashes}' in text:
        hashes += "#"
    return f'r{hashes}"{text}"{hashes}'


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    sys.path.insert(0, str(Path(sys.argv[1]).resolve()))
    from tools import approval_detection as d  # noqa: E402
    from tools import approval_windows_hardline as w  # noqa: E402

    out = [
        "//! Generated by `compat/generate_approval_tables.py` from the reference; do not edit by hand.",
        "",
        "/// `HARDLINE_PATTERNS`: (pattern, description, matched against the quote-masked variant).",
        "pub const HARDLINE_PATTERNS: &[(&str, &str, bool)] = &[",
    ]
    for pattern, description in d.HARDLINE_PATTERNS:
        masked = description in d._QUOTE_MASKED_HARDLINE_DESCRIPTIONS
        out.append(f"    ({raw(pattern)}, {raw(description)}, {str(masked).lower()}),")
    out.append("];")
    out += ["", "/// The `-WhatIf`-exempt rules without the exemption, by description.",
            "pub const WHATIF_STRICT_PATTERNS: &[(&str, &str)] = &["]
    for description, pattern in w.windows_whatif_strict_patterns(d._CMDPOS).items():
        out.append(f"    ({raw(description)}, {raw(pattern)}),")
    out.append("];")
    out += [
        "",
        f"pub const WHATIF_STATEMENT_UNGUARDED: &str = {raw(w._WHATIF_STATEMENT_UNGUARDED_RE.pattern)};",
        f"pub const WHATIF_OTHER_HARDLINE: &str = {raw(w._WHATIF_OTHER_HARDLINE_RE.pattern)};",
        "",
    ]
    Path(sys.argv[2]).write_text("\n".join(out), encoding="utf-8")
    print(f"{len(d.HARDLINE_PATTERNS)} hardline patterns, {len(w.windows_whatif_strict_patterns(d._CMDPOS))} strict")


if __name__ == "__main__":
    main()
